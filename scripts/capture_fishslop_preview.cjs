const {chromium} = require('../artifacts/toy2game/node_modules/playwright');
const fs = require('fs'),path=require('path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const context=await browser.newContext({viewport:{width:1200,height:800}});
 await context.route('**/api/toy-games/fishslop/save',r=>r.fulfill({json:{learnerId:700005,revision:0,storage:{},stats:{}}}));
 const page=await context.newPage();
 page.on('console',m=>{if(m.type()==='error')console.log(m.text())});
 await page.goto('http://localhost:8000/assets/games/fishslop/index.html?quality=low&scale=0.6');
 await page.locator('#btn-dive:not(:disabled)').waitFor({timeout:60000});
 await page.screenshot({path:path.join(root,'artifacts/fishslop-title-zh.png')});
 console.log('PASS: fresh Chinese title captured');
 await context.close();
 const touch=await browser.newContext({viewport:{width:1024,height:768},isMobile:true,hasTouch:true});
 await touch.route('**/api/toy-games/fishslop/save',r=>r.fulfill({json:{learnerId:700006,revision:0,storage:{},stats:{}}}));
 const tablet=await touch.newPage();const errors=[];tablet.on('pageerror',e=>errors.push(e.message));
 await tablet.goto('http://localhost:8000/assets/games/fishslop/index.html?scale=0.35');
 await tablet.locator('#btn-dive:not(:disabled)').waitFor({timeout:60000});
 await tablet.locator('#btn-dive').click({force:true});
 assert.equal(await tablet.evaluate(()=>window.__fishslop.quality),'low');
 await tablet.locator('.tbtn.feed').dispatchEvent('pointerdown',{pointerId:11});
 await tablet.waitForFunction(()=>window.__fishslop.sim.stats.pelletsDropped>0,null,{polling:100,timeout:20000});
 await tablet.locator('.tbtn.feed').dispatchEvent('pointerup',{pointerId:11});
 await tablet.locator('.tbtn[data-tap=sonar]').dispatchEvent('pointerdown',{pointerId:12});
 await tablet.locator('.tbtn[data-tap=sonar]').dispatchEvent('pointerup',{pointerId:12});
 await tablet.waitForFunction(()=>window.__fishslop.sim.sonarCooldown>0,null,{polling:100,timeout:20000});
 await tablet.screenshot({path:path.join(root,'artifacts/fishslop-tablet-zh.png')});
 await tablet.setViewportSize({width:768,height:1024});
 await tablet.screenshot({path:path.join(root,'artifacts/fishslop-tablet-portrait-zh.png')});
 assert(await tablet.locator('.touch-buttons').evaluate(el=>{const r=el.getBoundingClientRect();return r.right<=innerWidth&&r.bottom<=innerHeight&&r.left>=0&&r.top>=0;}));
 assert.deepEqual(errors,[]);
 console.log('PASS: tablet feeding/sonar, default low quality, landscape and portrait controls');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
