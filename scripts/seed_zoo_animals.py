ENTRY_RE = re.compile(r"\{\s*id:\s*'([^']+)'(.*?)\}", re.S)


def read_map_items():
    """Parse the ITEMS array out of data.js — the single source of truth."""
    text = DATA_JS.read_text(encoding="utf-8")
    start = text.index("export const ITEMS = [")
    end = text.index("export const ANIMAL_IDS", start)
    items = []
    for entry_id, rest in ENTRY_RE.findall(text[start:end]):
        kind = re.search(r"kind:\s*'([^']+)'", rest)
        cn = re.search(r"cn:\s*'([^']+)'", rest)
        emoji = re.search(r"emoji:\s*'([^']+)'", rest)
        items.append({
            "id": entry_id,
            "kind": kind.group(1) if kind else "",
            "cn": cn.group(1) if cn else entry_id,
            "emoji": emoji.group(1) if emoji else "",
            "lock": bool(re.search(r"lock:\s*true", rest)),
        })
    if not items:
        raise SystemExit(f"没能从 {DATA_JS} 里解析出任何条目")
    return items


def table_ready(cursor):
    cursor.execute("SHOW COLUMNS FROM store_items LIKE 'zoo_animal_id'")
    return bool(cursor.fetchone())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Report what would change without writing")
    parser.add_argument("--update-prices", action="store_true", help="Also refresh the price of existing rows")
    args = parser.parse_args()

    items = read_map_items()
    known_ids = set()
    catalog = []
    for item in items:
        if not item["lock"]:
            print(f"  ! {item['id']} 在 data.js 里没有 lock: true，地图上永远是基础场景，跳过不上架")
            continue
        detail = CATALOG.get(item["id"])
        if detail is None:
            print(f"  ! {item['id']} 没有在脚本的 CATALOG 里登记价格和文案，已跳过")
            continue
        category, price, description = detail
        known_ids.add(item["id"])
        catalog.append((
            item["id"],
            NAME_OVERRIDES.get(item["id"], "黏土" + item["cn"]),
            item["emoji"],
            price,
            f"【{category}】{description}",
        ))

    with mysql_connection() as connection:
        try:
            with connection.cursor() as cursor:
                if not table_ready(cursor):
                    raise SystemExit(
                        "store_items 还没有 zoo_animal_id 字段。先运行一次 python backend/server.py 完成建表。"
                    )
                cursor.execute("SELECT id,zoo_animal_id,name,price,description FROM store_items WHERE zoo_animal_id<>''")
                existing = {row["zoo_animal_id"]: row for row in cursor.fetchall()}
                missing = [row for row in catalog if row[0] not in existing]
                refresh = [row for row in catalog if row[0] in existing]
                stale = [row for row in existing.values() if row["zoo_animal_id"] not in known_ids]

                if args.dry_run:
                    known = ", ".join(sorted(existing)[:6]) or "（无）"
                    print(f"{DATA_JS.name} 里有 {len(items)} 个物品，其中 {len(known_ids)} 个需要上架。")
                    print(f"商店现有可解锁条目 {len(existing)} 个（例如 {known}…）")
                    print(f"将新增 {len(missing)} 个；将同步文案 {len(refresh)} 个；将下架 {len(stale)} 个。")
                    for entry_id, name, emoji, price, _ in missing:
                        print(f"  + {entry_id:<12} {name} {emoji}  ⭐{price}")
                    for row in stale:
                        print(f"  - {row['zoo_animal_id']:<12} {row['name']}（地图上不再有它，已下架）")
                    return

                for entry_id, name, emoji, price, description in missing:
                    cursor.execute(
                        "INSERT INTO store_items(name,emoji,description,price,kind,zoo_animal_id) "
                        "VALUES(%s,%s,%s,%s,'zoo_animal',%s)",
                        (name, emoji, description, price, entry_id),
                    )
                for entry_id, name, emoji, price, description in refresh:
                    if args.update_prices:
                        cursor.execute(
                            "UPDATE store_items SET name=%s,emoji=%s,price=%s,description=%s WHERE zoo_animal_id=%s",
                            (name, emoji, price, description, entry_id),
                        )
                    else:
                        # 文案（含【分类】标记）总是同步，价格保持不动
                        cursor.execute(
                            "UPDATE store_items SET name=%s,emoji=%s,description=%s WHERE zoo_animal_id=%s",
                            (name, emoji, description, entry_id),
                        )
                # 地图上已经不存在的东西：连它带出来的 owned_items 一起清掉
                for row in stale:
                    cursor.execute("DELETE FROM owned_items WHERE item_id=%s", (row["id"],))
                    cursor.execute("DELETE FROM store_items WHERE id=%s", (row["id"],))
                connection.commit()

                cursor.execute("SELECT COUNT(*) AS n FROM store_items WHERE zoo_animal_id<>''")
                total_rows = cursor.fetchone()["n"]
                cursor.execute("SELECT COALESCE(SUM(price),0) AS total FROM store_items WHERE zoo_animal_id<>''")
                total_points = cursor.fetchone()["total"]
                categories = {}
                for entry_id, _, _, _, description_text in catalog:
                    categories[description_text[1:description_text.index("】")]] = categories.get(
                        description_text[1:description_text.index("】")], 0) + 1
                print(f"新增 {len(missing)} 条；同步 {len(refresh)} 条；下架 {len(stale)} 条。")
                print(f"现在共有 {total_rows} 个可解锁对象（" +
                      "，".join(f"{name} {count} 个" for name, count in categories.items()) + "）；"
                      f"全部解锁需要 ⭐{total_points}。")
                for entry_id, name, emoji, price, _ in missing:
                    print(f"  + {entry_id:<12} {name} {emoji}  ⭐{price}")
                if missing == [] and stale == []:
                    print("目录已经和数据文件一致，没有需要新增或下架的条目。")
        except Exception:
            connection.rollback()
            raise


if __name__ == "__main__":
    main()
