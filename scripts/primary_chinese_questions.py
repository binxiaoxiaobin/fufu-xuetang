def reading(bank,index,grade,unit):
    s=make_scene(bank,index,grade);prefix='阅读原创短文《%s》：\n%s\n\n'%(s['title'],s['text']);out=[]
    facts=[('故事中的主要人物是谁？','person',['值班老师','路过的游客']),('事情主要发生在哪里？','place',['火车站候车室','高山营地']),('主人公最初想完成什么？','goal',['赶去参加运动会','购买一辆新自行车']),('主人公遇到了什么困难？','obstacle',['突然找不到住处','所有道路都结冰了']),('主人公怎样应对困难？','method',['立刻离开，再也不尝试','把困难完全交给别人']),('最后的结果是什么？','outcome',['原来的目标被完全放弃','没有采取任何行动']),('完成事情后，主人公感到怎样？','feeling',['绝望','愤怒'])]
    for question,key,wrong in facts:
        out.append(choice(prefix+question,s[key],wrong,'短文直接写出了“%s”，据此可以找到答案。'%s[key]))
    out.append(choice(prefix+'哪一项符合事情的发展顺序？','产生目标→遇到困难→寻找办法→获得结果',['获得结果→产生目标→遇到困难→寻找办法','寻找办法→获得结果→产生目标→遇到困难'],'先“想'+s['goal']+'”，再遇到“'+s['obstacle']+'”，接着采取办法，最后得到结果。'))
    out.append(choice(prefix+'根据短文，结果改变的主要原因是什么？','主人公根据困难采取了具体行动',['目标自己实现，没有采取行动','主人公不再关心目标'],'主人公采取了“'+s['method']+'”的行动，随后出现“'+s['outcome']+'”的结果，前后有明确的联系。'))
    summary=s['person']+'为'+s['goal']+'，克服困难并取得了结果'
    out.append(choice(prefix+'哪一句最能概括短文主要内容？',summary,['介绍火车站里所有旅客的故事','描写一场没有人物参加的比赛'],'概括应包括人物、目标、解决过程和结果。'+summary+'覆盖了短文的主要信息。'))
    return out


