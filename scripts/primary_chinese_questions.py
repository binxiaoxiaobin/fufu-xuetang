def make_scene(bank,index,grade):
    place,goal,obstacle,method,outcome,feeling,title=SCENES[bank][index%8]
    person=['小禾','小林','小雨','小舟','小宁','小岚','小安','小溪'][(index+grade)%8]
    text='%s来到%s，想%s。可是，%s。%s没有马上放弃，而是%s。最后，%s。想到自己的努力，%s感到%s。'%(person,place,goal,obstacle,person,method,outcome,person,feeling)
    if grade>=4:text+='离开时，%s把这次经历记在本子上，提醒自己遇到问题先寻找具体的办法。'%person
    return dict(text=text,person=person,place=place,goal=goal,obstacle=obstacle,method=method,outcome=outcome,feeling=feeling,title=title)


